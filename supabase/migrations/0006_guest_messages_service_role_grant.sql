-- Migration 0006: grant guest_messages DML to service_role
--
-- Migration 0005 created guest_messages and revoked PUBLIC/anon/authenticated,
-- matching the 0001/0004 boundary. Unlike the 0001 tables, the service-role
-- path was left without table privileges: service_role is NOT a superuser on
-- Supabase (rolsuper = false). It only holds BYPASSRLS, which skips row
-- policies, not table GRANTs. On this project the default privileges for
-- tables created by role postgres grant service_role only TRUNCATE /
-- REFERENCES / TRIGGER — no SELECT or INSERT — so the service-role client
-- fails with "permission denied for table guest_messages" (surfaced as a 500
-- from GET /api/admin/events/{id}/submissions via listSubmissions()).
--
-- The 0001 tables carry full service_role DML from the platform's earlier
-- default-privilege wiring; guest_messages missed it because it was created
-- after that wiring changed. This restores the server-only read/write path
-- for the new table without touching the anon/authenticated boundary.
--
-- Direct-pg paths (guest-message-tx-repo / getPgPool) connect as the table
-- owner and are unaffected either way.
--
-- Idempotent: safe to re-run (re-granting the same privileges is a no-op).

GRANT SELECT, INSERT ON guest_messages TO service_role;
